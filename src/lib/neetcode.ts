const BY_NAME = new Map(NEETCODE_250.map((p, i) => [p.name.toLowerCase(), i]))

const BY_SLUG = new Map<string, number>()
NEETCODE_250.forEach((p, i) => {
  for (const slug of p.slugs) if (!BY_SLUG.has(slug)) BY_SLUG.set(slug, i)
})

export function findNeetcodeIndex(name: string): number | null {
  const hit = BY_NAME.get(name.trim().toLowerCase())
  return hit === undefined ? null : hit
}

export function findNeetcodeBySlug(slug: string): number | null {
  const hit = BY_SLUG.get(slug.trim().toLowerCase())
  return hit === undefined ? null : hit
}
